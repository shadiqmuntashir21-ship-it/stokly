import { config } from "dotenv";
config({path:".env.local"});
const email=process.env.OWNER_EMAIL?.trim().toLowerCase();
const password=process.env.OWNER_PASSWORD;
const name=process.env.OWNER_NAME || "Owner STOKLY";
if (process.env.NODE_ENV==="production") throw new Error("Bootstrap tidak boleh dijalankan pada NODE_ENV production.");
if (process.env.STOKLY_BOOTSTRAP_ENABLED!=="1") throw new Error("Set STOKLY_BOOTSTRAP_ENABLED=1 hanya untuk bootstrap lokal.");
if (!email || !password || password.length < 12) throw new Error("OWNER_EMAIL dan OWNER_PASSWORD minimal 12 karakter wajib disediakan.");
const {auth}=await import("../src/lib/auth");
const {query}=await import("../src/lib/db");
await auth.api.signUpEmail({body:{email,password,name}});
const rows=await query<{id:string}>('SELECT id FROM "user" WHERE email=$1 LIMIT 1',[email]);
if(!rows[0]) throw new Error("Akun gagal dibuat.");
await query("INSERT INTO user_roles(user_id,role) VALUES($1,'owner') ON CONFLICT(user_id) DO NOTHING",[rows[0].id]);
console.log("Owner dibuat. Hapus OWNER_PASSWORD dan STOKLY_BOOTSTRAP_ENABLED dari lingkungan lokal.");
process.exit(0);
